import * as sudoku from "../sudoku.js";
import { processSettings } from "./processor.js";
import { RenbanLine } from "./renban.js";

declare const QUnit: any;

QUnit.module("constraints/renban");

QUnit.test("basic elimination", (assert: any) => {
  const constraint = new RenbanLine([
    [0, 0],
    [0, 1],
    [0, 2],
    [0, 3],
  ]);
  const settings = processSettings({ constraints: [constraint] });
  const board = sudoku.emptyBoard(9);
  board[0][0] = sudoku.bitMask(2);
  const next = sudoku.clone(board);
  constraint.performElimination(settings, board, next);
  assert.equal(
    sudoku.dump(next, { verbose: true }),
    `\
[ 2       ][1 345    ][1 345    ] [1 345    ][123456789][123456789] [123456789][123456789][123456789]
[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]
[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]

[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]
[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]
[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]

[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]
[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]
[123456789][123456789][123456789] [123456789][123456789][123456789] [123456789][123456789][123456789]`,
  );
});
